"""A tiny CPU learned-observer workflow, not a reproduction of research results.

Run from a checkout with: python examples/train_observer.py
Targets learn addition; observers see only saved weights. Target training and
measurement use the same 100 cases, so this is NOT unseen-input generalization.
All generated target files live in an automatically cleaned temporary directory.
"""
from pathlib import Path
import json
import sys
import tempfile

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import torch
from synaptic_lens.observer import (
    fit_lens, fit_ridge, layer_statistics, metrics, paired_run_bootstrap,
    predict_lens, predict_ridge, split_runs,
)
from synaptic_lens.structured import fit_structured, predict_structured
from synaptic_lens.targets import TargetConfig, generate_population


def run_demo(*, runs=20, steps=12, epochs=30):
    """Fixed tiny budget; test data never influences fitting or model selection."""
    if epochs < 1:
        raise ValueError("epochs must be positive")
    previous_threads = torch.get_num_threads()
    torch.set_num_threads(1)
    try:
        with tempfile.TemporaryDirectory(prefix="synaptic-lens-demo-") as output:
            path = generate_population(TargetConfig(runs=runs, steps=steps, seed=1729), output)
            # Only a file generated by this invocation is loaded, not an external checkpoint.
            data = torch.load(path, weights_only=True, map_location="cpu")
        partitions = split_runs(runs)
        weights, labels = data["weights"], data["loss"]
        train, validation, test = (partitions[k] for k in ("train", "validation", "test"))
        tx, vx = weights[train].flatten(0, 1), weights[validation].flatten(0, 1)
        ty, vy = labels[train].flatten(), labels[validation].flatten()
        layout = data["manifest"]["layout"]
        raw = fit_lens(tx, ty, vx, vy, epochs=epochs, seed=7)
        structured = fit_structured(tx, ty, vx, vy, layout, epochs=epochs, seed=7)
        statistics = fit_ridge(layer_statistics(tx, layout), ty,
                               layer_statistics(vx, layout), vy)
        truth = labels[test]
        predictions = {
            "train_mean": torch.full_like(truth, ty.mean()),
            "statistics_ridge": predict_ridge(statistics, layer_statistics(weights[test], layout)),
            "raw_weights": predict_lens(raw, weights[test]),
            "structured_weights": predict_structured(structured, weights[test]),
        }
        report = {
            "scope": "Tiny fixed-budget software demonstration, not research replication or evidence of superiority",
            "target_training_suite": "All 100 ordered digit pairs; measurement uses these same cases",
            "device": "cpu", "runs": runs, "target_steps": steps, "observer_epochs": epochs,
            "split_run_ids": {k: v.tolist() for k, v in partitions.items()},
            "selected_epoch": {"raw_weights": raw["best_epoch"], "structured_weights": structured["best_epoch"]},
            "statistics_ridge_alpha": statistics["alpha"],
            "test_metrics": {k: metrics(truth, p) for k, p in predictions.items()},
            "structured_vs_statistics_run_bootstrap": paired_run_bootstrap(
                truth, predictions["structured_weights"], predictions["statistics_ridge"]),
            "uncertainty_limit": "Illustrative whole-run resampling of a tiny test split; not independent observer or population replication",
        }
        return report
    finally:
        torch.set_num_threads(previous_threads)


if __name__ == "__main__":
    print(json.dumps(run_demo(), indent=2))
